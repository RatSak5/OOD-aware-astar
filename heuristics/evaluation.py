"""Raw-prediction heuristic quality and constraint-violation measurements."""

from __future__ import annotations

from collections import defaultdict
from typing import Any, Sequence

import numpy as np

from data.dataset import DatasetSample
from heuristics.cea import CEALossConfig
from heuristics.data import collate_heuristic_samples
from heuristics.losses import ConstraintAwareLossConfig, compute_heuristic_losses

try:
    import torch
except ImportError:  # pragma: no cover - depends on local packages
    torch = None  # type: ignore[assignment]

try:
    from tqdm.auto import tqdm
except ImportError:  # pragma: no cover - optional dependency
    def tqdm(iterable: Any, **kwargs: Any) -> Any:
        description = kwargs.get("desc", "Evaluating")
        total = len(iterable)

        def _iterate() -> Any:
            for index, item in enumerate(iterable, start=1):
                yield item
                print(f"\r{description}: {index}/{total}", end="", flush=True)
            if total:
                print()

        return _iterate()


def evaluate_heuristic_model(
    model: Any,
    samples: Sequence[DatasetSample],
    method: str,
    *,
    device: str = "cpu",
    composite: ConstraintAwareLossConfig = ConstraintAwareLossConfig(),
    cea: CEALossConfig = CEALossConfig(),
    violation_tolerance: float = 1e-6,
    progress_description: str | None = None,
) -> dict[str, dict[str, float]]:
    """Evaluate one map at a time and return overall and per-distribution rows.

    Constraint statistics use unmodified model predictions before any clipping,
    fallback, or correction. Consistency is checked on every valid directed
    edge generated by the shared movement function.
    """

    if torch is None:
        raise ImportError("Heuristic evaluation requires PyTorch.")
    if method not in {"H1", "H2", "H3"}:
        raise ValueError("method must be H1, H2, or H3.")
    if not np.isfinite(violation_tolerance) or violation_tolerance < 0:
        raise ValueError("violation_tolerance must be finite and non-negative.")
    if not samples:
        raise ValueError("Cannot evaluate an empty collection of maps.")

    model = model.to(device)
    model.eval()
    aggregates: dict[str, dict[str, Any]] = defaultdict(
        lambda: {
            "num_maps": 0,
            "num_cells": 0,
            "absolute_error_sum": 0.0,
            "squared_error_sum": 0.0,
            "admissibility_violations": 0,
            "maximum_overestimation": 0.0,
            "num_directed_edges": 0,
            "consistency_violations": 0,
            "maximum_consistency_violation": 0.0,
            "goal_prediction_error_sum": 0.0,
            "loss_total_sum": 0.0,
            "loss_fit_sum": 0.0,
            "loss_adm_sum": 0.0,
            "loss_cons_sum": 0.0,
            "loss_goal_sum": 0.0,
            "loss_cea_sum": 0.0,
        }
    )

    with torch.no_grad():
        for sample in tqdm(
            samples,
            desc=progress_description or f"Evaluating {method}",
            leave=False,
        ):
            batch = collate_heuristic_samples([sample], device=device)
            output = model(batch.inputs)
            total, terms, prediction = compute_heuristic_losses(
                method,
                output,
                batch.targets,
                batch.valid_mask,
                batch.edge_indices,
                batch.edge_costs,
                batch.goal_coordinates,
                composite=composite,
                cea=cea,
            )
            valid = batch.valid_mask[0]
            predicted_values = prediction[0][valid]
            target_values = batch.targets[0][valid]
            errors = predicted_values - target_values
            absolute_errors = errors.abs()
            overestimation = torch.relu(errors)

            if batch.edge_indices.numel():
                _, sources, destinations = batch.edge_indices.unbind(dim=1)
                flat_prediction = prediction.reshape(1, -1)
                consistency = (
                    flat_prediction[0, sources]
                    - batch.edge_costs
                    - flat_prediction[0, destinations]
                )
                positive_inconsistency = torch.relu(consistency)
            else:
                positive_inconsistency = torch.empty(0, device=prediction.device)

            row_keys = ("all", sample.grid_map.distribution)
            for row_key in row_keys:
                row = aggregates[row_key]
                row["num_maps"] += 1
                row["num_cells"] += int(valid.sum().item())
                row["absolute_error_sum"] += float(absolute_errors.sum().item())
                row["squared_error_sum"] += float(errors.square().sum().item())
                row["admissibility_violations"] += int(
                    (errors > violation_tolerance).sum().item()
                )
                if overestimation.numel():
                    row["maximum_overestimation"] = max(
                        row["maximum_overestimation"], float(overestimation.max().item())
                    )
                row["num_directed_edges"] += int(positive_inconsistency.numel())
                row["consistency_violations"] += int(
                    (positive_inconsistency > violation_tolerance).sum().item()
                )
                if positive_inconsistency.numel():
                    row["maximum_consistency_violation"] = max(
                        row["maximum_consistency_violation"],
                        float(positive_inconsistency.max().item()),
                    )
                goal_row, goal_col = sample.grid_map.goal
                row["goal_prediction_error_sum"] += float(
                    torch.abs(prediction[0, goal_row, goal_col] - batch.targets[0, goal_row, goal_col]).item()
                )
                row["loss_total_sum"] += float(total.item())
                for name in (
                    "loss_fit",
                    "loss_adm",
                    "loss_cons",
                    "loss_goal",
                    "loss_cea",
                ):
                    row[f"{name}_sum"] += float(terms[name].item())

    output_metrics: dict[str, dict[str, float]] = {}
    for distribution, row in aggregates.items():
        maps_count = max(int(row["num_maps"]), 1)
        cells_count = max(int(row["num_cells"]), 1)
        edge_count = max(int(row["num_directed_edges"]), 1)
        output_metrics[distribution] = {
            "distribution": distribution,
            "num_maps": float(row["num_maps"]),
            "num_cells": float(row["num_cells"]),
            "num_directed_edges": float(row["num_directed_edges"]),
            "loss_total": float(row["loss_total_sum"] / maps_count),
            "loss_fit": float(row["loss_fit_sum"] / maps_count),
            "loss_adm": float(row["loss_adm_sum"] / maps_count),
            "loss_cons": float(row["loss_cons_sum"] / maps_count),
            "loss_goal": float(row["loss_goal_sum"] / maps_count),
            "loss_cea": float(row["loss_cea_sum"] / maps_count),
            "heuristic_mae": float(row["absolute_error_sum"] / cells_count),
            "heuristic_rmse": float(np.sqrt(row["squared_error_sum"] / cells_count)),
            "admissibility_violation_pct": float(
                100.0 * row["admissibility_violations"] / cells_count
            ),
            "consistency_violation_pct": float(
                100.0 * row["consistency_violations"] / edge_count
                if row["num_directed_edges"]
                else 0.0
            ),
            "maximum_overestimation": float(row["maximum_overestimation"]),
            "maximum_consistency_violation": float(row["maximum_consistency_violation"]),
            "goal_prediction_error": float(row["goal_prediction_error_sum"] / maps_count),
        }
    return output_metrics
